// Renders brand/dist/<name>/sheet.md: the one-page brand sheet for a sub-brand (thesis,
// palettes, roles, proportion, type, do/don't, open questions), from its manifest and the
// resolved tokens. The guidelines site shows the same content at /subbrands/<name>.

const STATUS = { core: 'Core', locked: 'Locked', proposal: 'Proposal — for Jeremiah to confirm' };

export function renderSheet(resolved, config, prefixes, summary) {
  const { sb, tokens } = resolved;
  const m = sb.manifest;
  const ref = config.referenceMode;
  const L = [];
  const add = (s = '') => L.push(s);
  const val = (key, mode = ref) => {
    const t = tokens.find((x) => x.key === key);
    return t ? (t.modeDependent ? t.raw[mode] : t.raw[ref]) : '?';
  };

  add(`<!-- GENERATED by brand/scripts/build.mjs from ${sb.isCore ? 'brand/core.json' : `brand/subbrands/${sb.name}/subbrand.json`} — do not edit. -->`);
  add(`# ${m.label} — brand sheet`);
  add();
  add(`**${STATUS[m.status]}** · ${m.product ?? 'Beatham'} · platforms: ${m.platforms.join(', ')} · CSS \`--${prefixes.css}-*\` · Swift \`${prefixes.swift}Tokens\``);
  add();
  add(`> ${m.thesis}`);
  add();
  if (m.summary) {
    add(m.summary);
    add();
  }
  add('## Palettes');
  const pal = m.palettes;
  add(`- **Accent:** \`${pal.accent}\`${pal.accent === 'neutral' ? ' (no hue: selection is neutral)' : ` — accent.fill ${val('color.accent.fill')} dark / ${val('color.accent.fill', 'light')} light`}. Marks only what you act on.`);
  if (pal.secondary?.length) add(`- **Secondary:** ${pal.secondary.map((p) => `\`palette.${p}\``).join(', ')}`);
  if (pal.tertiary?.length) add(`- **Tertiary:** ${pal.tertiary.map((p) => `\`palette.${p}\``).join(', ')}`);
  add(`- **Chrome hues:** ${summary.roles.chromeHues.join(', ') || 'none'} (budget ${summary.roles.budget})${Object.keys(summary.roles.scopedHues).length ? ` · scoped: ${Object.entries(summary.roles.scopedHues).map(([s, h]) => `${s} → ${h.join(', ')}`).join('; ')}` : ''}`);
  add();
  add('## Proportion');
  for (const system of [m.proportion, ...(m.proportion.alternates ?? [])]) {
    add(`- **${system.name}:** ${system.parts.map((p) => `${p.pct} ${p.label}`).join(' · ')}`);
  }
  add();
  if (m.roles?.length) {
    add('## Product roles');
    add('| Group | What it marks | Note |');
    add('|---|---|---|');
    for (const r of m.roles) add(`| \`color.${r.group}.*\` | ${r.label} | ${r.note ?? ''} |`);
    add();
  }
  if (m.rules?.grants?.length) {
    add('## Hue grants (on top of the core rules)');
    for (const g of m.rules.grants) add(`- \`${g.ramp}\` → ${g.roles.map((r) => `\`${r}\``).join(', ')} (${g.scope}) — ${g.reason}`);
    add();
  }
  if (m.type?.length) {
    add('## Type');
    for (const t of m.type) add(`- ${t}`);
    add();
  }
  if (m.layout?.length) {
    add('## Layout');
    for (const t of m.layout) add(`- ${t}`);
    add();
  }
  add('## Do');
  for (const d of m.do) add(`- ${d}`);
  add();
  add("## Don't");
  for (const d of m.dont) add(`- ${d}`);
  add();
  if (m.openQuestions?.length) {
    add('## Open questions for Jeremiah');
    m.openQuestions.forEach((q, i) => add(`${i + 1}. ${q}`));
    add();
  }
  add('## Checks');
  add(`- Contrast: ${summary.contrast.checks} pair checks across ${resolved.modeNames.length} modes, ${summary.contrast.failing} failing.`);
  for (const [mode, r] of Object.entries(summary.contrast.tightest)) add(`  - tightest in ${mode}: ${r.ratio}:1 (min ${r.min}) ${r.fg} on ${r.bg}`);
  add(`- Roles: ${summary.roles.checked} colour values across 4 modes keep to the hue budget and the accent rule.`);
  return L.join('\n') + '\n';
}
