// Renders brand/dist/<name>/tokens.json: the flat token list (every value in every mode, with its
// CSS and Swift names), the sub-brand's manifest and its check summary. The guidelines site reads it;
// so can any tool (Figma variable import, a design-QA script).
import { swiftName } from './format-swift.mjs';
import { varName } from './format-css.mjs';

const plain = (v) => (v && typeof v === 'object' ? JSON.parse(JSON.stringify(v)) : v);

export function renderData(resolved, config, prefixes, summary) {
  const { sb, modeNames, tokens } = resolved;
  const data = {
    generated: `GENERATED by brand/scripts/build.mjs from brand/tokens${sb.isCore ? '' : ` + brand/subbrands/${sb.name}`} — do not edit. Regenerate: npm run brand:build`,
    subbrand: sb.name,
    manifest: sb.manifest,
    prefix: prefixes,
    modes: modeNames.map((m) => ({ id: m, label: config.modes[m].label })),
    referenceMode: config.referenceMode,
    summary,
    tokens: tokens.map((t) => ({
      key: t.key,
      group: t.path[0],
      type: t.type,
      description: t.description,
      reference: typeof t.original === 'string' && t.original.startsWith('{') ? t.original : null,
      name: t.name,
      css: varName(prefixes.css, t),
      swift: swiftName(t, prefixes.swift),
      modeDependent: t.modeDependent,
      values: t.modeDependent ? Object.fromEntries(modeNames.map((m) => [m, plain(t.raw[m])])) : { all: plain(t.raw[config.referenceMode]) },
    })),
  };
  return JSON.stringify(data, null, 2) + '\n';
}
