// Renders CSS custom properties from resolved tokens.
//
// Per-project file (brand/dist/<name>/tokens.css):
//   - Mode-independent tokens go on :root once.
//   - Every mode gets a full colour block on an attribute selector, so any element can be scoped
//     to a mode (`data-theme` + `data-contrast`) — specimens in several modes side by side.
//   - Before JS sets data-theme / data-contrast, the OS preference decides (prefers-color-scheme,
//     prefers-contrast), so a project is on-brand with zero setup.
//   - Reduced motion swaps each motion duration for its reduced variant.
//
// Site bundle (brand/site/src/generated/brand.css): every sub-brand, scoped under
// [data-subbrand="<name>"], always with the core prefix, so the guidelines can switch sub-brands.

export const varName = (prefix, t) => `--${prefix}-${t.name}`;

/** Expands composite tokens into one or more [name, value] declarations. */
export function declarations(t, mode, prefix) {
  const v = t.css[mode];
  const n = varName(prefix, t);
  switch (t.type) {
    case 'typography':
      return [
        [`${n}-font-family`, v.fontFamily],
        [`${n}-font-size`, v.fontSize],
        [`${n}-font-weight`, String(v.fontWeight)],
        [`${n}-line-height`, String(v.lineHeight)],
        [`${n}-letter-spacing`, v.letterSpacing],
        [n, `${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${v.fontFamily}`],
      ];
    case 'material':
      return [
        [`${n}-blur`, v.blur],
        [`${n}-opacity`, String(v.opacity)],
      ];
    case 'haptic':
      return []; // Apple platforms only; documented from tokens.json.
    default:
      if (Array.isArray(v) || (v && typeof v === 'object')) throw new Error(`No CSS rendering for ${t.key} (${t.type})`);
      return [[n, String(v)]];
  }
}

const block = (selector, lines, indent = '') =>
  `${indent}${selector.replace(/\n/g, `\n${indent}`)} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`;

function modeLines({ tokens }, mode, prefix) {
  const lines = [];
  for (const t of tokens.filter((x) => x.modeDependent)) {
    if (t.key === 'color-scheme') lines.push(`color-scheme: ${t.css[mode]};`);
    for (const [n, v] of declarations(t, mode, prefix)) lines.push(`${n}: ${v};`);
  }
  return lines;
}

const independentLines = ({ tokens }, ref, prefix) =>
  tokens.filter((t) => !t.modeDependent).flatMap((t) => declarations(t, ref, prefix)).map(([n, v]) => `${n}: ${v};`);

const reducedLines = ({ tokens }, ref, prefix) =>
  tokens
    .filter((t) => t.path[0] === 'motion' && t.path.at(-1) === 'duration-reduced')
    .map((t) => `${varName(prefix, t).replace(/-reduced$/, '')}: ${t.css[ref]};`);

export function renderCss(resolved, config, prefix) {
  const ref = config.referenceMode;
  const { sb } = resolved;
  const out = [
    `/*
 * GENERATED by Style Dictionary from brand/tokens/${sb.isCore ? '' : ` + brand/subbrands/${sb.name}/`} — do not edit.
 * Beatham ${sb.isCore ? 'core' : `sub-brand: ${sb.manifest.label}`}. Regenerate: npm run brand:build${sb.isCore ? '' : ` -- --subbrand ${sb.name}`}
 * Modes: set data-theme="dark|light" and data-contrast="standard|more" on <html> (or any element);
 * until then the OS preference decides.
 */
`,
  ];
  out.push(block(':root', independentLines(resolved, ref, prefix)));
  for (const mode of resolved.modeNames) {
    out.push(`\n/* Mode: ${config.modes[mode].label} */\n`);
    out.push(block(config.modes[mode].css, modeLines(resolved, mode, prefix)));
  }
  const nested = (media, selector, mode) =>
    `@media ${media} {\n${block(selector, modeLines(resolved, mode, prefix), '  ')}}\n`;
  out.push('\n/* System preference before data-theme / data-contrast are set */\n');
  out.push(nested('(prefers-color-scheme: light)', ':root:not([data-theme])', 'light'));
  out.push(nested('(prefers-contrast: more)', ':root:not([data-theme]):not([data-contrast])', 'high-contrast-dark'));
  out.push(nested('(prefers-color-scheme: light) and (prefers-contrast: more)', ':root:not([data-theme]):not([data-contrast])', 'high-contrast-light'));
  out.push('\n/* Reduced motion: movement becomes an instant change or a short cross-fade */\n');
  out.push(`@media (prefers-reduced-motion: reduce) {\n  :root {\n${reducedLines(resolved, ref, prefix).map((l) => `    ${l}`).join('\n')}\n  }\n}\n`);
  return out.join('');
}

/**
 * The guidelines site's stylesheet. For each sub-brand S:
 *   [data-subbrand=S]                                   mode-independent tokens + dark (default)
 *   [data-subbrand=S][data-theme=M], [data-subbrand=S] [data-theme=M]   each mode, on <html> or a specimen
 * Specimens never nest one sub-brand inside another (the site shows other sub-brands' colours from data).
 */
export function renderSiteCss(all, config, prefix) {
  const ref = config.referenceMode;
  const out = [
    `/*
 * GENERATED by brand/scripts/build.mjs — do not edit. Every Beatham sub-brand, scoped under
 * [data-subbrand="<name>"], in every mode. Regenerate: npm run brand:build
 */
`,
  ];
  for (const resolved of all) {
    const s = `[data-subbrand="${resolved.sb.name}"]`;
    out.push(`\n/* ===== ${resolved.sb.manifest.label} ===== */\n`);
    out.push(block(s, [...independentLines(resolved, ref, prefix), ...modeLines(resolved, ref, prefix)]));
    for (const mode of resolved.modeNames) {
      const m = config.modes[mode].site;
      out.push(block(`${s}${m},\n${s} ${m}`, modeLines(resolved, mode, prefix)));
    }
    out.push(`@media (prefers-reduced-motion: reduce) {\n  ${s} {\n${reducedLines(resolved, ref, prefix).map((l) => `    ${l}`).join('\n')}\n  }\n}\n`);
  }
  return out.join('');
}
